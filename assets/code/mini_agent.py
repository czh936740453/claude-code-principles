"""
mini_agent.py —— 认识「代理」的最小雏形（配合第 1 章）

代理 = 一个循环：读目标 -> 决定 -> 动手 -> 看结果 -> 再决定。
这里用函数调用模拟「模型思考」，去掉所有复杂部分，只看骨架。

用法:
    python mini_agent.py
"""


def 模型思考(任务, 已做):
    """模拟大模型：按顺序给出下一步动作（真实实现是调用 API）。"""
    if 已做 == 0:
        return "先读取待办文件"
    if 已做 == 1:
        return "打印待办事项"
    return "全部完成"


def 动手(动作):
    """模拟代理执行动作（真实实现是调用 Bash/读文件等工具）。"""
    print("   [执行]", 动作)
    return "ok"


def main():
    任务 = "帮我整理今日待办"
    print("用户:", 任务)
    for 步 in range(5):                      # 循环：代理的本体
        下一步 = 模型思考(任务, 步)            # 1) 感知 + 决策
        if 下一步 == "全部完成":
            break
        动手(下一步)                          # 2) 行动
    print("代理: 任务结束")


if __name__ == "__main__":
    main()